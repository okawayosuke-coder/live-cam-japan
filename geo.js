// 最長一致で地名→座標を引く（部分文字列シャドウ回避）。日本語キーは toLowerCase の影響を受けない。
export function geocodeTitle(text = "", regionId = null) {
  const t = text.toLowerCase();
  let best = null, bestLen = -1;
  for (const [name, lat, lng] of GAZETTEER) {
    if (name.length > bestLen && t.includes(name.toLowerCase())) { best = { lat, lng, approx: true }; bestLen = name.length; }
  }
  if (best) return best;
  if (regionId && REGION_CENTER[regionId]) {
    const [lat, lng] = REGION_CENTER[regionId];
    return { lat, lng, approx: true };
  }
  return null;
}
